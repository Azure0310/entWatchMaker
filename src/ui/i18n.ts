export type StringKey = keyof typeof strings.ja;

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = strings[lang][key] ?? strings.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('entwatchmaker.lang');
    if (saved === 'ja' || saved === 'en') return saved;
  } catch {
    // ignore
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}
